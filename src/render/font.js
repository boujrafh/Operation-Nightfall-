export const CHARS = Object.keys(GLYPHS);

/** Glyphs drawn with 1-pixel strokes so their inner lines stay visible. */
const THIN = new Set(['W']);
export const CELL = 8;

/** Bitmap font with one baked atlas per palette colour (lazy). */
export class BitmapFont {
  constructor() {
    /** @type {Map<number, HTMLCanvasElement>} */
    this.atlases = new Map();
    /** @type {Map<string, number>} */
    this.index = new Map(CHARS.map((c, i) => [c, i]));
  }

  /** @param {number} colorIdx */
  atlas(colorIdx) {
    let a = this.atlases.get(colorIdx);
    if (a) return a;
    a = makeCanvas(CHARS.length * CELL, CELL);
    const ctx = a.getContext('2d');
    ctx.fillStyle = PALETTE[colorIdx];
    CHARS.forEach((ch, i) => {
      const g = GLYPHS[ch];
      for (let y = 0; y < 7; y++) {
        const row = g[y];
        for (let x = 0; x < 5; x++) {
          if (row[x] !== '#') continue;
          // Bold: widen each pixel to the right, unless that would close a
          // one-pixel gap (keeps W, M and N readable).
          const widen = !THIN.has(ch) && (row[x + 1] === '#' || row[x + 2] !== '#');
          ctx.fillRect(i * CELL + 1 + x, y, widen ? 2 : 1, 1);
        }
      }
    });
    this.atlases.set(colorIdx, a);
    return a;
  }

  /** @param {string} text @param {number} [scale] */
  measure(text, scale = 1) {
    return text.length * CELL * scale;
  }

  /**
   * @param {CanvasRenderingContext2D} ctx
   * @param {string} text
   * @param {number} x
   * @param {number} y
   * @param {number} colorIdx
   * @param {{ scale?: number, shadow?: number, align?: 'left'|'center'|'right' }} [opts]
   */
  draw(ctx, text, x, y, colorIdx, opts = {}) {
    const scale = opts.scale || 1;
    const str = String(text).toUpperCase();
    let sx = Math.round(x);
    if (opts.align === 'center') sx = Math.round(x - this.measure(str, scale) / 2);
    else if (opts.align === 'right') sx = Math.round(x - this.measure(str, scale));
    const sy = Math.round(y);
    if (opts.shadow !== undefined) {
      this.draw(ctx, str, sx + scale, sy + scale, opts.shadow, { scale });
    }
    const atlas = this.atlas(colorIdx);
    const q = this.index.get('?');
    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      if (ch === ' ') continue;
      const gi = this.index.has(ch) ? this.index.get(ch) : q;
      ctx.drawImage(
        atlas,
        gi * CELL,
        0,
        CELL,
        CELL,
        sx + i * CELL * scale,
        sy,
        CELL * scale,
        CELL * scale,
      );
    }
  }
}

/**
 * Splits text into lines of at most `max` characters, breaking on spaces.
 * @param {string} text @param {number} max
 */
export function wrapText(text, max) {
  const words = String(text).split(/\s+/).filter(Boolean);
  const lines = [];
  let cur = '';
  for (const w of words) {
    if (!cur) cur = w;
    else if (cur.length + 1 + w.length <= max) cur += ' ' + w;
    else {
      lines.push(cur);
      cur = w;
    }
    while (cur.length > max) {
      lines.push(cur.slice(0, max));
      cur = cur.slice(max);
    }
  }
  if (cur) lines.push(cur);
  return lines;
}
